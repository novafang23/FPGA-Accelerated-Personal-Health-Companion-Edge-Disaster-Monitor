#!/usr/bin/env python3
"""bundle_desktop_dashboard.py — Compresses valor_dashboard.html to a Gzip C header.

Project: VALOR (SIH26181)
Produces: firmware/shrikefi/valor_dashboard_gz.h
Enables the ESP32-S3 SoftAP to serve the rich aesthetic desktop dashboard over Wi-Fi
at http://192.168.4.1/desktop using minimal flash and RAM (<35 KB).
"""

import gzip
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
HTML_PATH = REPO_ROOT / "firmware" / "shrikefi" / "dashboard" / "valor_dashboard.html"
OUT_HEADER = REPO_ROOT / "firmware" / "shrikefi" / "valor_dashboard_gz.h"

def bundle():
    if not HTML_PATH.is_file():
        print(f"ERROR: Dashboard file not found at {HTML_PATH}", file=sys.stderr)
        sys.exit(1)

    raw_bytes = HTML_PATH.read_bytes()
    raw_len = len(raw_bytes)

    # Use gzip level 9 with mtime=0 for bit-exact reproducible builds
    gz_bytes = gzip.compress(raw_bytes, compresslevel=9, mtime=0)
    gz_len = len(gz_bytes)
    ratio = (gz_len / raw_len) * 100.0

    lines = [
        "/*",
        " * valor_dashboard_gz.h — Pre-compressed Gzip desktop dashboard for ShrikeFi SoftAP",
        " * Auto-generated by scripts/bundle_desktop_dashboard.py — DO NOT EDIT MANUALLY",
        f" * Source: firmware/shrikefi/dashboard/valor_dashboard.html ({raw_len:,} bytes)",
        f" * Compressed: {gz_len:,} bytes ({ratio:.1f}% of original size)",
        " */",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "static const uint8_t VALOR_DASHBOARD_GZ[] = {",
    ]

    # Format bytes in rows of 16 for clean C code
    for i in range(0, gz_len, 16):
        chunk = gz_bytes[i:i + 16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        if i + 16 < gz_len:
            hex_str += ","
        lines.append(f"    {hex_str}")

    lines.extend([
        "};",
        "",
        "static const size_t VALOR_DASHBOARD_GZ_LEN = sizeof(VALOR_DASHBOARD_GZ);",
        "",
    ])

    OUT_HEADER.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"SUCCESS: Bundled {HTML_PATH.name}")
    print(f"  Raw size:        {raw_len:,} bytes ({raw_len / 1024.0:.1f} KB)")
    print(f"  Compressed Gzip: {gz_len:,} bytes ({gz_len / 1024.0:.1f} KB, {ratio:.1f}%)")
    print(f"  Generated:       {OUT_HEADER.relative_to(REPO_ROOT)}")

if __name__ == "__main__":
    bundle()
